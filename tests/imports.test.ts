import { describe, expect, test } from "bun:test";
import * as fs from "node:fs";
import * as path from "node:path";
import { makeCrankProject, runCli } from "./helpers.ts";

const ONE_LINE = "export const v = 1;\n";

function scanIndex(files: Record<string, string>, outside?: (root: string) => void) {
  const root = makeCrankProject(files);
  outside?.(root);
  const run = runCli(root, ["scan"]);
  expect(run.status).toBe(0);
  const index = JSON.parse(fs.readFileSync(path.join(root, ".crank/anatomy-index.json"), "utf-8"));
  const anatomy = fs.readFileSync(path.join(root, ".crank/anatomy.md"), "utf-8");
  return { root, index, anatomy };
}

describe("TS/JS imports", () => {
  const outsideName = `outside-${process.pid}-${Date.now()}`;
  const A_TS = [
    'import { b } from "./b";',
    'import "./side.js";',
    'export * from "../lib/util";',
    "import {",
    "  x,",
    '} from "./multi.ts";',
    'const c = require("./c.cjs");',
    'const d = await import("./d.mjs");',
    'import React from "react";',
    'import fs from "node:fs";',
    'import { y } from "@/alias";',
    'import { self } from "./a";',
    'import { b as b2 } from "./b";',
    'import "./e";',
    'import "./both.js";',
    'import "./view.js";',
    'import secret from "./credentials";',
    'import hidden from "./.hidden/conf";',
    `import out from "../../${outsideName}";`,
    "",
  ].join("\n");
  const files: Record<string, string> = {
    "src/a.ts": A_TS,
    "src/c.cjs": 'const b = require("./b");\n',
    "src/d.mjs": 'import "./b";\n',
    "tests/x.test.ts": 'import { b } from "../src/b";\n',
    "gen/g.ts": '// Code generated by tool. DO NOT EDIT.\nimport { b } from "../src/b";\n',
    "notes.md": 'import "./src/b"\n',
  };
  for (const rel of [
    "src/b.ts",
    "src/side.ts",
    "lib/util/index.ts",
    "src/multi.ts",
    "src/e.ts",
    "src/e.js",
    "src/both.js",
    "src/both.ts",
    "src/view.tsx",
    "src/credentials.ts",
    "src/.hidden/conf.ts",
  ]) {
    files[rel] = ONE_LINE;
  }
  const numbers = Array.from({ length: 51 }, (_, i) => String(i + 1).padStart(2, "0"));
  files["src/many.ts"] = numbers.map((n) => `import "./m/f${n}";\n`).join("");
  for (const n of numbers) files[`src/m/f${n}.ts`] = ONE_LINE;
  files["src/big.ts"] = 'import { b } from "./b";\n' + "// pad\n".repeat(37450);
  const { index, anatomy } = scanIndex(files, (root) =>
    fs.writeFileSync(path.join(root, "..", `${outsideName}.ts`), ONE_LINE),
  );

  test("resolve and record in source order", () => {
    expect(index.version).toBe(2);
    expect(index.files["src/a.ts"].imports).toEqual([
      "src/b.ts",
      "src/side.ts",
      "lib/util/index.ts",
      "src/multi.ts",
      "src/c.cjs",
      "src/d.mjs",
      "src/e.ts",
      "src/both.js",
      "src/view.tsx",
    ]);
    expect(index.files["tests/x.test.ts"].imports).toEqual(["src/b.ts"]);
    expect(index.files["gen/g.ts"].imports).toEqual(["src/b.ts"]);
    expect(index.files["src/c.cjs"].imports).toEqual(["src/b.ts"]);
    expect(index.files["src/d.mjs"].imports).toEqual(["src/b.ts"]);
  });

  test("a file with no resolvable imports, or of an unsupported extension, carries no imports key", () => {
    expect(index.files["src/b.ts"]).toBeDefined();
    expect("imports" in index.files["src/b.ts"]).toBe(false);
    expect(index.files["notes.md"]).toBeDefined();
    expect("imports" in index.files["notes.md"]).toBe(false);
  });

  test("at most 50 entries, the first 50 in source order", () => {
    const imports = index.files["src/many.ts"].imports;
    expect(imports).toHaveLength(50);
    expect(imports[0]).toBe("src/m/f01.ts");
    expect(imports[49]).toBe("src/m/f50.ts");
  });

  test("a file longer than 262,144 UTF-16 code units records no imports", () => {
    expect(files["src/big.ts"]!.length).toBeGreaterThan(262_144);
    expect(index.files["src/big.ts"]).toBeDefined();
    expect("imports" in index.files["src/big.ts"]).toBe(false);
  });

  test("anatomy.md never shows imports", () => {
    expect(anatomy).toContain("`src/side.ts`");
    const lines = anatomy.split("\n");
    expect(lines.filter((l) => l.includes("src/a.ts") && l.includes("src/side.ts"))).toEqual([]);
  });
});
