import * as fs from "node:fs";
import * as path from "node:path";

// One-line file descriptions for the anatomy index. First hit wins:
// package.json "description", known filename, any .json "description",
// markdown heading, Python module docstring, comments above the first line of
// code, first declaration. Reads at most HEAD_BYTES; result capped at
// MAX_DESC_CHARS.

const HEAD_BYTES = 12 * 1024;
export const MAX_DESC_CHARS = 150;

// In these, a line starting with `#` is a preprocessor directive, never a comment.
const C_FAMILY = new Set([".c", ".h", ".cc", ".cpp", ".hpp", ".hh", ".cxx", ".m", ".mm"]);
// Data files have no prose header: only a JSON "description" field describes them.
const DATA_EXTENSIONS = new Set([".json", ".jsonl", ".ndjson", ".csv", ".tsv"]);
// Copyright and license text.
const BOILERPLATE =
  /copyright|\(c\)|©|licen[cs]e|spdx|this file is part of|all rights reserved|free software/i;
// Tool directives that live in comments but describe nothing.
const DIRECTIVE = /^(?:@(?!generated)|-\*-|shellcheck|eslint|ts-|type:|coding[:=]|noinspection)/i;
// Generator banners: "Code generated by sqlc. DO NOT EDIT.", "@generated by
// protoc-gen-es", "This file was automatically generated by …", "Generated by CMake".
const GENERATED =
  /^\W*(?:@generated\b|(?:code |this file (?:is |was |has been )?)?(?:auto(?:matically)?[- ]?)?generated(?: by\b|\b.*\bdo not edit\b))/i;
const GENERATED_SCAN_LINES = 10;

const KNOWN_FILENAMES: Record<string, string> = {
  "package.json": "Package manifest",
  "package-lock.json": "npm lockfile",
  "pnpm-lock.yaml": "pnpm lockfile",
  "bun.lock": "bun lockfile",
  "tsconfig.json": "TypeScript compiler configuration",
  "cargo.toml": "Rust package manifest",
  "go.mod": "Go module definition",
  "pyproject.toml": "Python project configuration",
  "requirements.txt": "Python dependencies",
  makefile: "Build targets",
  dockerfile: "Container image definition",
  ".gitignore": "Git ignore patterns",
  ".gitattributes": "Git attributes",
  license: "License",
  "license.md": "License",
  "license.txt": "License",
};

function cap(s: string): string {
  const oneLine = s.replace(/\s+/g, " ").trim();
  return oneLine.length > MAX_DESC_CHARS ? oneLine.slice(0, MAX_DESC_CHARS - 1) + "…" : oneLine;
}

function readHead(filePath: string): string {
  const fd = fs.openSync(filePath, "r");
  try {
    const buf = Buffer.alloc(HEAD_BYTES);
    const n = fs.readSync(fd, buf, 0, HEAD_BYTES, 0);
    return buf.toString("utf-8", 0, n);
  } finally {
    fs.closeSync(fd);
  }
}

/** First markdown heading, or first non-empty line. */
function fromMarkdown(head: string): string | null {
  const m = head.match(/^#{1,3}\s+(.+)$/m);
  if (m) return m[1]!;
  const firstLine = head.split("\n").find((l) => l.trim().length > 0);
  return firstLine ?? null;
}

/** Python module docstring: a string literal as the first statement (it may outrun the head). */
function fromModuleDocstring(head: string): string | null {
  const m = head.match(/^(?:[ \t]*(?:#.*)?\r?\n)*[ \t]*[rRuU]?("""|''')([\s\S]*?)(?:\1|$)/);
  return (
    m?.[2]!
      .split("\n")
      .map((l) => l.trim())
      .find(Boolean) ?? null
  );
}

interface CommentLine {
  text: string;
  inBlock: boolean;
  /** The line closes a comment run: a block's end, a blank line, a shebang or a directive. */
  endsRun: boolean;
}

/** One line inside or opening a `/* *\/` block; null when code follows the `*\/`. */
function blockCommentLine(line: string, inBlock: boolean): CommentLine | null {
  const body = inBlock ? line : line.slice(2);
  const end = body.indexOf("*/");
  if (end < 0) return { text: body.replace(/^\*+|\*+$/g, ""), inBlock: true, endsRun: false };
  if (body.slice(end + 2).trim()) return null; // code follows on the same line
  return { text: body.slice(0, end).replace(/^\*+|\*+$/g, ""), inBlock: false, endsRun: true };
}

/** Classifies one line of the leading comments; null at the first line of code. */
function commentLine(raw: string, inBlock: boolean, cFamily: boolean): CommentLine | null {
  const line = raw.trim();
  let parsed: CommentLine | null;
  if (inBlock || line.startsWith("/*")) {
    parsed = blockCommentLine(line, inBlock);
  } else if (line.startsWith("//")) {
    parsed = { text: line.replace(/^\/+!?/, ""), inBlock: false, endsRun: false };
  } else if (line.startsWith("#") && !cFamily && !line.startsWith("#!")) {
    parsed = { text: line.replace(/^#+/, ""), inBlock: false, endsRun: false };
  } else if (line && !line.startsWith("#")) {
    return null;
  } else {
    // blank line, shebang or C preprocessor directive
    return { text: "", inBlock: false, endsRun: true };
  }
  if (!parsed) return null;
  const text = parsed.text.trim();
  return { ...parsed, text: cFamily && text.startsWith("#") ? "" : text }; // commented-out directive
}

/**
 * First useful line of the `//`, `#` and `/* *\/` comments above the first
 * line of code. Skips directives and punctuation-only lines; copyright or
 * license text skips the rest of its comment run (a block, or line comments
 * up to a blank line).
 */
function fromLeadingComments(head: string, cFamily: boolean): string | null {
  let inBlock = false;
  let skipping = false;
  for (const raw of head.split("\n")) {
    const line = commentLine(raw, inBlock, cFamily);
    if (!line) break;
    inBlock = line.inBlock;
    if (BOILERPLATE.test(line.text)) skipping = true;
    else if (!skipping && /[\p{L}\p{N}]/u.test(line.text) && !DIRECTIVE.test(line.text))
      return line.text;
    if (line.endsRun) skipping = false;
  }
  return null;
}

/** Fall back to the first exported/top-level declaration name. */
function fromDeclaration(head: string): string | null {
  const m = head.match(
    /^(?:export\s+)?(?:default\s+)?(?:async\s+)?(function|class|const|interface|type|def|struct|enum|fn|func)\s+\*?\s*([A-Za-z_$][\w$]*)/m,
  );
  if (m) return `Defines ${m[2]}`;
  return null;
}

export function describeFile(filePath: string): string {
  const base = path.basename(filePath).toLowerCase();
  const known = KNOWN_FILENAMES[base];

  let head: string;
  try {
    head = readHead(filePath);
  } catch {
    return known ?? "";
  }

  const ext = path.extname(base);
  if (base === "package.json") {
    // Prefer the manifest's own description over the generic label.
    const desc = jsonDescription(head);
    if (desc) return desc;
  }
  if (known) return known;
  if (ext === ".json") {
    const desc = jsonDescription(head);
    if (desc) return desc;
  }
  return proseDescription(head, ext) ?? "";
}

/** A JSON document's "description" string, capped; null when it has none. */
function jsonDescription(head: string): string | null {
  try {
    const desc = JSON.parse(head).description;
    if (typeof desc === "string" && desc) return cap(desc);
  } catch {}
  return null;
}

/** Markdown heading for prose files, then docstring, comments or declaration for code. */
function proseDescription(head: string, ext: string): string | null {
  if (ext === ".md" || ext === ".rst" || ext === ".adoc" || ext === ".txt") {
    const d = fromMarkdown(head);
    if (d) return cap(d);
  }
  if (DATA_EXTENSIONS.has(ext)) return "";
  const docstring = ext === ".py" || ext === ".pyi" ? fromModuleDocstring(head) : null;
  const d = docstring ?? fromLeadingComments(head, C_FAMILY.has(ext)) ?? fromDeclaration(head);
  return d ? cap(d) : null;
}

/** True when one of the file's first lines is a generator banner. */
export function isGenerated(head: string): boolean {
  return head.split("\n", GENERATED_SCAN_LINES).some((line) => GENERATED.test(line));
}
